#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const registryPath = join(root, 'contracts/system-backup/v12/metrics-alert-registry.json');
const outputPath = join(root, 'contracts/system-backup/v12/prometheus-alert-rules.yaml');
const quote = (value) => JSON.stringify(value);

export function renderPrometheusRules(registry, sourceHash) {
  if (registry.registry_version !== 'system-backup-metrics-alerts.v1' || registry.contract_version !== 'system-backup-plan.v12') {
    throw new Error('unexpected system backup metrics registry version');
  }
  if (!Array.isArray(registry.alerts) || registry.alerts.length !== registry.source.alert_count) {
    throw new Error('system backup alert inventory is incomplete');
  }
  const seenIDs = new Set();
  const seenNames = new Set();
  const lines = [
    '# Generated from metrics-alert-registry.json. Do not edit this file directly.',
    '# DO NOT LOAD: no rule loader, missing-series execution, or PromQL fixture validation exists yet.',
    `# Source SHA-256: ${sourceHash}`,
    'groups:',
    '  - name: clawmanager-system-backup',
    '    rules:',
  ];
  let compiled = 0;
  for (const alert of registry.alerts) {
    if (!/^[a-z][a-z0-9.-]*$/.test(alert.id) || seenIDs.has(alert.id)) {
      throw new Error(`invalid or duplicate alert ID: ${alert.id}`);
    }
    seenIDs.add(alert.id);
    if (!['promql', 'controller_state'].includes(alert.expression_language)) {
      throw new Error(`unknown evaluator for ${alert.id}`);
    }
    if (alert.expression_language === 'controller_state') {
      continue;
    }
    const name = `ClawManagerSystemBackup_${alert.id.replaceAll(/[.-]/g, '_')}`;
    if (seenNames.has(name)) throw new Error(`colliding Prometheus alert name: ${name}`);
    seenNames.add(name);
    if (typeof alert.expression !== 'string' || !alert.expression.trim() ||
        !Number.isSafeInteger(alert.for_seconds) || alert.for_seconds < 0 ||
        !['warning', 'critical', 'info'].includes(alert.severity) ||
        !Array.isArray(alert.profiles) || alert.profiles.length === 0 ||
        alert.profiles.some((profile) => !['production', 'development'].includes(profile))) {
      throw new Error(`invalid Prometheus rule metadata: ${alert.id}`);
    }
    lines.push(`      - alert: ${name}`);
    lines.push(`        expr: ${quote(alert.expression)}`);
    lines.push(`        for: ${alert.for_seconds}s`);
    lines.push('        labels:');
    lines.push(`          severity: ${quote(alert.severity)}`);
    lines.push('        annotations:');
    for (const [key, value] of Object.entries({
      contract_rule_id: alert.id,
      runbook: alert.runbook,
      profiles: alert.profiles.join(','),
      threshold_source: alert.threshold_source,
      dedupe_key: alert.dedupe_key.join(','),
      missing_series: alert.missing_series,
      counter_reset: alert.counter_reset,
      recovery_condition: alert.recovery_condition,
    })) {
      if (typeof value !== 'string') throw new Error(`missing ${key} for ${alert.id}`);
      lines.push(`          ${key}: ${quote(value)}`);
    }
    compiled++;
  }
  if (compiled + registry.alerts.filter((alert) => alert.expression_language === 'controller_state').length !== registry.alerts.length) {
    throw new Error('not every system backup alert was assigned an evaluator');
  }
  return `${lines.join('\n')}\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const source = readFileSync(registryPath, 'utf8');
  const registry = JSON.parse(source);
  const sourceHash = createHash('sha256').update(source).digest('hex');
  const rendered = renderPrometheusRules(registry, sourceHash);
  if (process.argv.includes('--write')) {
    writeFileSync(outputPath, rendered, 'utf8');
  } else if (process.argv.includes('--check')) {
    if (readFileSync(outputPath, 'utf8') !== rendered) {
      console.error('prometheus-alert-rules.yaml is stale; run node scripts/system-backup-prometheus-rules.mjs --write');
      process.exitCode = 1;
    }
  } else {
    process.stdout.write(rendered);
  }
}
