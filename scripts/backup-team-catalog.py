"""Regenerate the reviewed integration catalog without changing historical SQL.

--check is read-only. Run --write only after reviewing new migration contents.
The generated constants remain checked by the independent Go catalog algorithm.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parent.parent


def registry_summary(objects):
    statuses = {"owner_recorded", "pending_owner_review", "frozen"}
    if any(obj["decision_status"] not in statuses for obj in objects):
        raise ValueError("Unknown registry decision requires review")
    identities = [(obj["object_type"], obj["name"]) for obj in objects]
    if len(set(identities)) != len(identities):
        raise ValueError("Duplicate registry object")
    recorded = [obj for obj in objects if obj["decision_status"] in {"owner_recorded", "frozen"}]
    return {
        "object_count": len(objects), "policy_recorded": len(recorded),
        "policy_pending": len(objects) - len(recorded),
        "cross_review_pending": sum(bool(set(obj.get("required_cross_reviewers", [])) -
            set(obj.get("approved_cross_reviewers", []))) for obj in recorded),
    }


def outputs():
    files = sorted((ROOT / "backend/internal/db/migrations").glob("*.sql"))
    digest = hashlib.sha256(b"system-backup-migration-catalog.v1\0")
    for file in files:
        for value in (file.name.encode(), file.read_bytes().replace(b"\r\n", b"\n").replace(b"\r", b"\n")):
            digest.update(struct.pack(">Q", len(value)))
            digest.update(value)
    catalog = {"algorithm": "sha256-length-prefixed-filename-normalized-content-v1",
               "file_count": len(files), "hash": digest.hexdigest()}
    generated = ('// Code generated by scripts/backup-team-catalog.py; DO NOT EDIT.\n'
                 'package migrationcatalog\n\n'
                 f'const ReviewedHash = "{catalog["hash"]}"\n'
                 f'const ReviewedFileCount = {len(files)}\n')
    yield ROOT / "backend/internal/migrationcatalog/reviewed_catalog.go", generated
    yield ROOT / "docs/backup-team-integration/catalog.json", json.dumps(catalog, indent=2) + "\n"
    # Refresh only the directory identity. Draft policies and human reviews are
    # preserved; freshness is not permission to activate a collector.
    registry_path = ROOT / "contracts/system-backup/v12/schema-registry.json"
    schema_registry = json.loads(registry_path.read_text(encoding="utf-8"))
    schema_registry["migration_catalog"] = catalog
    schema_registry["summary"] = registry_summary(schema_registry["objects"])
    registry_json = json.dumps(schema_registry, indent=2, ensure_ascii=False) + "\n"
    yield registry_path, registry_json
    yield ROOT / "backend/internal/systembackupbusinessa/testdata/schema-registry.json", registry_json
    mapping = json.loads((ROOT / "docs/backup-team-integration/sql-map.json").read_text(encoding="utf-8"))
    tables = sorted(mapping["tables"].values())
    registry = ('// Code generated from the reviewed SQL identifier map; DO NOT EDIT.\n'
                'package systembackup\n\n'
                '// Versioned control rows are historical metadata, never restored as runnable work.\n'
                'func init() {\n\tcontrolTables = append(controlTables,\n' +
                ''.join(f'\t\t"{table}",\n' for table in tables + [
                    "system_backup_v2_engine_bindings", "system_backup_v2_import_journal",
                    # Readiness and immutable queued inputs are installation-local
                    # execution authority, never restored as runnable work.
                    "system_backup_v2_execution_readiness", "system_backup_v2_execution_inputs",
                    "system_backup_v2_execution_plans",
                    "system_backup_v2_job_send_intents",
                    "system_backup_v2_runtime_resources", "system_backup_v2_runtime_writers",
                    "system_backup_v2_runtime_captures", "system_backup_v2_runtime_stop_proofs",
                ]) + '\t)\n}\n')
    yield ROOT / "backend/internal/systembackup/v2_control_registry.go", registry


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in outputs():
        actual = path.read_text(encoding="utf-8") if path.exists() else None
        if actual == content:
            continue
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
        else:
            stale.append(path.relative_to(ROOT).as_posix())
    if stale:
        print("Reviewed integration artifacts are stale: " + ", ".join(stale), file=sys.stderr)
        return 1
    print("Reviewed migration catalog and control-table classification match")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
