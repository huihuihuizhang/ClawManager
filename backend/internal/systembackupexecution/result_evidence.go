var formalResultID = regexp.MustCompile(`^sev_[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$`)

// A content-addressed UUID keeps retries on the same original Job/report. It
// grants no authority: the caller must lock the Job and compare every byte.
func resultEvidenceRef(a d.Authority, j d.JobBinding, digest string) d.EvidenceRef {
	return resultEvidenceCoordinates(a.InstallationID, a.TaskPublicID, a.AttemptNo, a.Phase, j, digest)
}

// Pure historical identity calculation, without constructing an old live claim.
func resultEvidenceCoordinates(installation, backup string, attempt uint64, phase string, j d.JobBinding, digest string) d.EvidenceRef {
	raw, _ := json.Marshal([]any{"public-job-result.v1", installation, backup, attempt, phase, j.JobUnitKey, j.UID, j.Generation, digest})
	sum := sha256.Sum256(raw)
	sum[6] = (sum[6] & 15) | 0x80
	sum[8] = (sum[8] & 63) | 0x80
	return d.EvidenceRef{PublicID: fmt.Sprintf("sev_%x-%x-%x-%x-%x", sum[:4], sum[4:6], sum[6:8], sum[8:10], sum[10:16]), SHA256: digest}
}

// The inline profile admits only the fixed successful B report generated by
// this owner: no free-text warning, caller evidence, or additional statistics.
// The original plan validator separately binds every checkpoint and Job field.
func inlineResultBody(raw []byte) bool {
	if len(raw) == 0 || len(raw) > 8192 {
		return false
	}
	var r d.ModuleResult
	if json.Unmarshal(raw, &r) != nil || r.Status != "completed" || r.FailureCategory != "none" || r.Warnings == nil || len(r.Warnings) != 0 || r.EvidenceIDs == nil || len(r.EvidenceIDs) != 0 || len(r.Statistics) != 5 {
		return false
	}
	for _, key := range []string{"files", "bytes", "rows", "tables", "sealed_bytes"} {
		if _, ok := r.Statistics[key]; !ok {
			return false
		}
	}
	// Require the owner's exact encoding, including closed field sets.
	canonical, err := json.Marshal(r)
	return err == nil && bytes.Equal(canonical, raw)
}

// Called only inside saveResult's original authority/Job transaction. Inline
// registration is publication; no external object or TaskRuntime log grant is
// involved. Capacity, lifecycle and final authority recheck remain mandatory.
func (o *PublicJobOwner) registerResult(ctx context.Context, tx *sql.Tx, a d.Authority, j d.JobBinding, raw []byte) error {
	if a.TaskType != "backup" || !inlineResultBody(raw) {
		return c.ErrExecutionRecord
	}
	ref := resultEvidenceRef(a, j, hash(raw))
	var stored []byte
	var schema, ownerType, owner, kind, state, digest, media, encryption, classification, failure, health string
	var size int64
	var expires time.Time
	// The original Job is already exclusively locked by saveResult. Evidence
	// bytes are append-only for this account: a shared record/gap lock protects
	// their comparison without granting UPDATE merely for a locking read.
	err := tx.QueryRowContext(ctx, `SELECT schema_version,owner_target_type,owner_target_public_id,evidence_type,storage_state,inline_payload,content_checksum,content_size_bytes,media_type,encryption,redaction_classification,evidence_failure_code,observed_health,expires_at FROM system_backup_v2_evidence WHERE public_id=? FOR SHARE`, ref.PublicID).Scan(&schema, &ownerType, &owner, &kind, &state, &stored, &digest, &size, &media, &encryption, &classification, &failure, &health, &expires)
	if err == nil {
		var now time.Time
		if tx.QueryRowContext(ctx, "SELECT UTC_TIMESTAMP(6)").Scan(&now) != nil || schema != "system-backup-evidence.v1" || ownerType != "backup" || owner != a.TaskPublicID || kind != "diagnostic" || state != "inline" || !bytes.Equal(stored, raw) || digest != ref.SHA256 || size != int64(len(raw)) || media != "application/json" || encryption != "none" || classification != "internal" || failure != "none" || health != "healthy" || !now.Before(expires) {
			return c.ErrExecutionRecord
		}
		return nil
	}
	if err != sql.ErrNoRows {
		return err
	}
	var capacity, retention int64
	if err = tx.QueryRowContext(ctx, `SELECT control_metadata_capacity_bytes,evidence_retention_seconds FROM system_backup_v2_configs WHERE origin_installation_id=? AND version=?`, a.InstallationID, a.ConfigVersion).Scan(&capacity, &retention); err != nil {
		return err
	}
	if retention < 86400 || retention > 31536000 {
		return c.ErrExecutionRecord
	}
	if err = (security.RegistrationCapacity{ReportFile: o.Gate.Records.CapacityReportFile}).Reserve(ctx, tx, capacity, len(raw)); err != nil {
		return err
	}
	result, err := tx.ExecContext(ctx, `INSERT INTO system_backup_v2_evidence (public_id,owner_target_type,owner_target_public_id,evidence_type,storage_state,inline_payload,content_checksum,content_size_bytes,media_type,encryption,redaction_classification,observed_health,expires_at,protected_until,created_at) VALUES (?,'backup',?,'diagnostic','inline',?,?,?,'application/json','none','internal','healthy',TIMESTAMPADD(SECOND,?,UTC_TIMESTAMP(6)),TIMESTAMPADD(SECOND,?,UTC_TIMESTAMP(6)),UTC_TIMESTAMP(6))`, ref.PublicID, a.TaskPublicID, raw, ref.SHA256, len(raw), retention, retention)
	if err != nil {
		return err
	}
	n, err := result.RowsAffected()
	if err != nil || n != 1 {
		return c.ErrExecutionRecord
	}
	return nil
}

func completedWorkerRelay(a d.Authority, j d.JobBinding, ref d.EvidenceRef) (*b.RelayMessage, error) {
	if !formalResultID.MatchString(ref.PublicID) {
		return nil, c.ErrExecutionRecord
	}
	m, err := workerRelayTemplate(a, j, "acquire")
	if err != nil {
		return nil, err
	}
	m.Sequence, m.Status, m.ResultEvidence = "3", "completed", &b.RelayEvidence{PublicID: ref.PublicID, SHA256: ref.SHA256}
	if err = b.RelayProgress("running", *m, b.RelayAdvance); err != nil {
		return nil, err
	}
	return m, nil
}
