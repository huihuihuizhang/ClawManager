func newMinioSeptemberTerminalComponent(t *testing.T, scenario string) *minioTerminalComponent {
	t.Helper()
	profile, _ := ma.NativeProfile(ma.SeptemberPermissionProfile)
	f := &minioTerminalComponent{scenario: scenario}
	f.model = &minioTerminalComponentSQL{f: f, rowVersion: 1}
	dir := t.TempDir()
	if e := os.Chmod(dir, 0700); e != nil {
		t.Fatal(e)
	}
	writeRaw := func(name string, raw []byte) (string, string) {
		path := filepath.Join(dir, name)
		if e := os.WriteFile(path, raw, 0600); e != nil {
			t.Fatal(e)
		}
		return path, hash(raw)
	}
	write := func(name string, value any) (string, string) {
		raw, e := ce.Canonical(value)
		if e != nil {
			t.Fatal(e)
		}
		return writeRaw(name, raw)
	}
	var e error
	f.public, f.key, e = ed25519.GenerateKey(rand.Reader)
	if e != nil {
		t.Fatal(e)
	}
	t.Cleanup(func() { clear(f.key) })
	f.config, e = sec.DecodeBootstrapConfig(componentConfigValues(t))
	if e != nil {
		t.Fatal(e)
	}
	now := time.Now().UTC().Truncate(time.Microsecond)
	start, end := now.Add(-time.Minute), now.Add(2*time.Minute)
	f.grant = sec.OfflineBootstrapGrant{InstallationID: "installation_terminal_minio", ServerUUID: "12345678-1234-1234-1234-123456789abc", Database: "original_terminal_minio", Username: "original-terminal-admin", UserID: 41, MatrixKey: "k8s-cluster", ConfigSHA256: f.config.SHA256(), IdempotencyKey: "original-terminal-minio-idempotency", ChangeReason: "original finite terminal source component"}
	f.input.GrantFile, f.input.GrantSHA256 = write("bootstrap-grant.json", sec.BootstrapGrantFile{SchemaVersion: "system-backup-offline-bootstrap-grant.v1", NotBefore: start, ExpiresAt: end, Grant: f.grant})
	byPurpose := map[string]sec.BootstrapSecretRef{}
	for _, ref := range f.config.References() {
		byPurpose[ref.Purpose] = ref
	}
	// Reuse the real five-role S3 protocol server. A front TLS server below
	// serves native permission APIs and forwards the SAME signed S3 request,
	// preserving its signed Host, through a separately CA+SPKI pinned TLS hop.
	// No signature is regenerated by either fixture server.
	f.protocol = minioTerminalProtocolFixtureNew(t, scenario)
	p := f.protocol.p
	p.target.InstallationID = f.grant.InstallationID
	p.target.Root = f.grant.InstallationID + "/"
	p.target.RemoteStagingRoot = f.grant.InstallationID + "_staging/"
	p.catalog.InstallationID = f.grant.InstallationID
	p.catalog.Root = f.grant.InstallationID + "/catalog/"
	in := &f.protocol.intent
	in.Version = profile.Protocol
	in.InstallationID = f.grant.InstallationID
	in.NotBefore = start
	in.Until = end
	in.ArtifactKey = p.target.RemoteStagingRoot + "bootstrap-probes/" + in.Nonce + "/protocol.bin"
	in.ArtifactBadChecksumKey = p.target.RemoteStagingRoot + "bootstrap-probes/" + in.Nonce + "/reject-checksum.bin"
	in.CatalogKey = p.catalog.Root + "bootstrap-probes/" + in.Nonce + "/protocol.json"
	in.CatalogBadChecksumKey = p.catalog.Root + "bootstrap-probes/" + in.Nonce + "/reject-checksum.json"
	f.input.CapabilityIntentFile, f.input.CapabilityIntentSHA256 = write("capability-intent.json", in)
	native := minioPermissionFixture(t)
	native.responses["server"] = map[string]any{"deploymentID": "deployment", "region": "us-east-1", "servers": []any{map[string]any{"state": "ok", "version": profile.ServerVersion, "commitID": profile.ServerCommit}}}
	for i := range p.uses {
		u := &p.uses[i]
		ref := byPurpose[u.principal.Purpose]
		u.principal.IdentityHash, u.principal.RefVersion = ref.IdentityHash, ref.Version
		u.principal.AccountSHA256 = hash([]byte(u.credential.AccessKey))
		u.principal.PolicyName = u.principal.Purpose
		u.bucket, u.root, u.staging = p.target.Bucket, p.target.Root, p.target.RemoteStagingRoot
		if strings.HasPrefix(u.principal.Purpose, "catalog_") {
			u.bucket, u.root, u.staging = p.catalog.Bucket, p.catalog.Root, ""
		}
		u.credential.NotBefore, u.credential.Until = start, now.Add(5*time.Minute)
		rules, err := minioPermissionObjectRulesV2(u.principal.Purpose, u.bucket, u.root, u.staging)
		if err != nil {
			t.Fatal(err)
		}
		u.principal.PolicySHA256 = minioProducerComponentPolicy(t, native, u.principal.PolicyName, rules)
		native.responses["user:"+u.credential.AccessKey] = map[string]any{"userAuthInfo": map[string]any{"type": "builtin", "authServerUserID": u.credential.AccessKey}, "policyName": u.principal.PolicyName, "status": "enabled", "updatedAt": now}
	}
	observer := nativePublicationCredential{AccessKey: "original-observer", SecretKey: "original-terminal-observer-private-secret", NotBefore: start, Until: now.Add(5 * time.Minute)}
	native.configuration.ObserverAccountSHA256 = hash([]byte(observer.AccessKey))
	native.configuration.ObserverPolicySHA256 = minioProducerComponentPolicy(t, native, native.configuration.ObserverPolicyName, minioPermissionObserverRulesV2(p.uses))
	native.responses["user:"+observer.AccessKey] = map[string]any{"userAuthInfo": map[string]any{"type": "builtin", "authServerUserID": observer.AccessKey}, "policyName": native.configuration.ObserverPolicyName, "status": "enabled", "updatedAt": now}
	backendProvider := p.grant.Provider
	backendURL, _ := url.Parse(backendProvider.Endpoint)
	backend, e := newMinioPermissionHTTP(backendProvider, observer)
	if e != nil {
		t.Fatal(e)
	}
	t.Cleanup(backend.close)
	server := httptest.NewTLSServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		f.requests.Add(1)
		if f.model.open.Load() != 0 {
			t.Error("concrete terminal performed provider I/O under SQL lock")
		}
		if !strings.HasPrefix(r.URL.Path, "/minio/admin/") && r.URL.Path != "/artifacts" && r.URL.Path != "/catalog" {
			forward := r.Clone(r.Context())
			copyURL := *r.URL
			copyURL.Scheme, copyURL.Host = backendURL.Scheme, backendURL.Host
			forward.URL = &copyURL
			forward.RequestURI = ""
			response, err := backend.client.Do(forward)
			if err != nil {
				t.Error("original signed S3 TLS fixture forward", err)
				w.WriteHeader(502)
				return
			}
			defer response.Body.Close()
			for name, values := range response.Header {
				for _, value := range values {
					w.Header().Add(name, value)
				}
			}
			w.WriteHeader(response.StatusCode)
			_, _ = io.Copy(w, response.Body)
			return
		}
		var caller *minioPermissionUse
		for i := range p.uses {
			u := &p.uses[i]
			if minioTerminalTestSignature(r, nil, u.credential.AccessKey, u.credential.SecretKey) {
				caller = u
				break
			}
		}
		isObserver := minioTerminalTestSignature(r, nil, observer.AccessKey, observer.SecretKey)
		if isObserver {
			caller = &minioPermissionUse{principal: minioPermissionPrincipal{PolicyName: native.configuration.ObserverPolicyName}, credential: observer}
		}
		if caller == nil {
			t.Error("invalid native permission SigV4")
			w.WriteHeader(403)
			return
		}
		if r.URL.Path == "/minio/admin/v3/accountinfo" {
			policy := native.responses["policy:"+caller.principal.PolicyName].(map[string]any)["Policy"]
			_ = json.NewEncoder(w).Encode(map[string]any{"AccountName": caller.credential.AccessKey, "Policy": policy, "Server": map[string]any{"Type": 3}, "Buckets": nil})
			return
		}
		if r.URL.Path == minioEffectiveOwnerGuardPath {
			w.WriteHeader(403)
			_ = json.NewEncoder(w).Encode(minioEffectiveGuardFixtureError())
			return
		}
		if !isObserver {
			t.Error("ordinary role substituted for native observer")
			w.WriteHeader(403)
			return
		}
		responseKey := ""
		switch r.URL.Path {
		case "/minio/admin/v3/info":
			responseKey = "server"
		case "/minio/admin/v3/user-info":
			responseKey = "user:" + r.URL.Query().Get("accessKey")
		case "/minio/admin/v3/info-canned-policy":
			responseKey = "policy:" + r.URL.Query().Get("name")
		case "/artifacts", "/catalog":
			if r.URL.RawQuery == "policy=" {
				w.WriteHeader(404)
				w.Write([]byte(`<Error><Code>NoSuchBucketPolicy</Code></Error>`))
				return
			}
			if r.URL.RawQuery == "versioning=" {
				w.Write([]byte(`<VersioningConfiguration><Status>Enabled</Status></VersioningConfiguration>`))
				return
			}
		}
		response := native.responses[responseKey]
		if response == nil {
			t.Error("unexpected native permission source request")
			w.WriteHeader(404)
			return
		}
		if f.scenario == "unknown-native-version" && responseKey == "server" {
			response = map[string]any{"deploymentID": "deployment", "region": "us-east-1", "servers": []any{map[string]any{"state": "ok", "version": "unknown", "commitID": profile.ServerCommit}}}
		}
		_ = json.NewEncoder(w).Encode(response)
	}))
	t.Cleanup(server.Close)
	ca := pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: server.Certificate().Raw})
	caFile, caHash := writeRaw("native-ca.pem", ca)
	provider := minioPermissionProvider{Endpoint: server.URL, Region: "us-east-1", CAFile: caFile, CASHA256: caHash, SPKISHA256: hash(server.Certificate().RawSubjectPublicKeyInfo), DeploymentID: "deployment", Deployment: minioPermissionObject{"minio", "minio-deployment-uid"}, ReplicaSet: minioPermissionObject{"minio-rs", "minio-rs-uid"}, Pod: minioPermissionObject{"minio-pod", "minio-pod-uid"}, Service: minioPermissionObject{"minio", "minio-service-uid"}, ServiceAccount: minioPermissionObject{"minio", "minio-sa-uid"}, Container: "minio", ImageID: "sha256:original-image", Node: "original-node", NodeUID: "original-node-uid"}
	p.grant = minioPermissionGrant{Version: "minio-permission-grant.v1", Installation: f.grant.InstallationID, Namespace: "original-terminal", NamespaceUID: "original-terminal-uid", ConfigSHA256: f.config.SHA256(), Profile: profile.Permission, Epoch: 1, NotBefore: start, Until: end, Provider: provider}
	files, pins := map[string]string{}, map[string]string{}
	for _, u := range p.uses {
		p.grant.Principals = append(p.grant.Principals, u.principal)
		files[u.principal.Purpose], pins[u.principal.Purpose] = write(u.principal.Purpose+".credential", u.credential)
	}
	p.target = PublicationTargetMaterials{Version: publicationTargetVersion, InstallationID: f.grant.InstallationID, Endpoint: provider.Endpoint, Region: provider.Region, Bucket: p.target.Bucket, Root: p.target.Root, RemoteStagingRoot: p.target.RemoteStagingRoot, ReadIdentityHash: byPurpose["artifact_read"].IdentityHash, ReadRefVersion: byPurpose["artifact_read"].Version, WriteIdentityHash: byPurpose["artifact_write"].IdentityHash, WriteRefVersion: byPurpose["artifact_write"].Version, DeleteIdentityHash: byPurpose["artifact_delete"].IdentityHash, DeleteRefVersion: byPurpose["artifact_delete"].Version, CAIdentityHash: hash([]byte("original-ca-identity")), CARefVersion: "original-ca-1", CAFile: provider.CAFile, CASHA256: provider.CASHA256, ReadCredentialFile: files["artifact_read"], ReadCredentialSHA256: pins["artifact_read"], WriteCredentialFile: files["artifact_write"], WriteCredentialSHA256: pins["artifact_write"], DeleteCredentialFile: files["artifact_delete"], DeleteCredentialSHA256: pins["artifact_delete"]}
	p.catalog = PublicationCatalogMaterials{Version: publicationCatalogMaterialsVersion, InstallationID: f.grant.InstallationID, Endpoint: provider.Endpoint, Region: provider.Region, Bucket: p.catalog.Bucket, Root: p.catalog.Root, ReadIdentityHash: byPurpose["catalog_read"].IdentityHash, ReadRefVersion: byPurpose["catalog_read"].Version, AppendIdentityHash: byPurpose["catalog_append"].IdentityHash, AppendRefVersion: byPurpose["catalog_append"].Version, CAIdentityHash: p.target.CAIdentityHash, CARefVersion: p.target.CARefVersion, CAFile: provider.CAFile, CASHA256: provider.CASHA256, ReadCredentialFile: files["catalog_read"], ReadCredentialSHA256: pins["catalog_read"], AppendCredentialFile: files["catalog_append"], AppendCredentialSHA256: pins["catalog_append"]}
	p.target.CatalogMaterialsFile, p.target.CatalogMaterialsSHA256 = write("catalog-materials.json", p.catalog)
	configFile, configSHA := writeRaw("config.json", f.config.CanonicalJSON())
	targetFile, targetSHA := write("target-materials.json", p.target)
	observerFile, observerSHA := write("observer.credential", observer)
	grantRaw, _ := ce.Canonical(p.grant)
	var exported install.MinIOPermissionGrant
	if json.Unmarshal(grantRaw, &exported) != nil {
		t.Fatal("original grant conversion")
	}
	definition := install.MinIOPermissionDefinition{Version: profile.Definition, ConfigFile: configFile, ConfigSHA256: configSHA, TargetFile: targetFile, TargetSHA256: targetSHA, GrantName: "original-permission-grant", HeadName: "original-permission-head", Grant: exported, ObserverCredentialFile: observerFile, ObserverCredentialSHA256: observerSHA, ObserverAccountSHA256: hash([]byte(observer.AccessKey)), ObserverPolicyName: native.configuration.ObserverPolicyName, ObserverPolicySHA256: native.configuration.ObserverPolicySHA256}
	f.input.DefinitionFile, f.input.DefinitionSHA256 = write("definition.json", definition)
	obj := func(v minioPermissionObject) ma.ObjectIdentity { return ma.ObjectIdentity{Name: v.Name, UID: v.UID} }
	target := ma.Target{InstallationID: f.grant.InstallationID, ServerUUID: f.grant.ServerUUID, Database: f.grant.Database, ConsumerDatabaseAccount: "original_consumer@localhost", ClusterUID: "original-cluster", Namespace: p.grant.Namespace, NamespaceUID: p.grant.NamespaceUID}
	enrollment := ma.Enrollment{ID: "original-enrollment", Revision: 1, ConfigMapName: "original-enrollment", ConfigMapUID: "original-enrollment-uid", DocumentSHA256: ma.Digest(hash([]byte("original-enrollment"))), PlanSHA256: ma.Digest(hash([]byte("original-plan"))), IssuerID: "original-issuer", IssuerPublicSHA256: ma.Digest(hash(f.public)), OwnerSubject: "original-owner", OwnerUID: "original-owner-uid", OwnerGroupsSHA256: ma.Digest(hash([]byte("original-groups")))}
	permissionHead := minioPermissionHead{Version: "minio-permission-head.v1", Installation: target.InstallationID, State: "active", GrantSHA256: hash(grantRaw), Epoch: 1, NotBefore: start, Until: end}
	headRaw, _ := ce.Canonical(permissionHead)
	permissionSource := ma.PermissionSource{Profile: profile.Permission, Grant: ma.ObjectIdentity{Name: definition.GrantName, UID: "original-grant-uid"}, Head: ma.ObjectIdentity{Name: definition.HeadName, UID: "original-head-uid"}, GrantSHA256: ma.Digest(hash(grantRaw)), InitialHeadSHA256: ma.Digest(hash(headRaw)), ObserverAccountSHA256: ma.Digest(definition.ObserverAccountSHA256), ObserverCredentialFileSHA256: ma.Digest(observerSHA), ObserverLocatorSHA256: ma.Digest(hash([]byte(observerFile))), ObserverPolicyName: definition.ObserverPolicyName, ObserverNormalizedPolicySHA256: ma.Digest(definition.ObserverPolicySHA256)}
	f.input.PermissionSource.File, f.input.PermissionSource.SHA256 = write("permission-source.json", minioEffectivePermissionConfiguration{Version: profile.Source, Installation: target.InstallationID, Namespace: target.Namespace, NamespaceUID: target.NamespaceUID, Issuer: f.public, MinimumEpoch: 1, Grant: minioPermissionObject{Name: permissionSource.Grant.Name, UID: permissionSource.Grant.UID}, Head: minioPermissionObject{Name: permissionSource.Head.Name, UID: permissionSource.Head.UID}, GrantSHA256: string(permissionSource.GrantSHA256), ObserverCredentialFile: observerFile, ObserverCredentialSHA256: observerSHA, ObserverAccountSHA256: definition.ObserverAccountSHA256, ObserverPolicyName: definition.ObserverPolicyName, ObserverPolicySHA256: definition.ObserverPolicySHA256})
	imageFile, imageSHA := write("image-provenance.json", MinIOBootstrapImageProvenance{Version: "original-minio-image-provenance.v1", ImageID: provider.ImageID, ServerVersion: profile.ServerVersion, ServerCommit: profile.ServerCommit})
	f.input.ProvenanceFile = imageFile
	sqlProvider := ma.Provider{IdentityProfile: profile.Provider, Endpoint: provider.Endpoint, Region: provider.Region, DeploymentID: provider.DeploymentID, CASHA256: ma.Digest(provider.CASHA256), SPKISHA256: ma.Digest(provider.SPKISHA256), ServerVersion: profile.ServerVersion, ServerCommit: profile.ServerCommit, ImageProvenanceSHA256: ma.Digest(imageSHA), Deployment: obj(provider.Deployment), ReplicaSet: obj(provider.ReplicaSet), Pod: obj(provider.Pod), Service: obj(provider.Service), ServiceAccount: obj(provider.ServiceAccount), Container: provider.Container, ImageID: provider.ImageID, Node: provider.Node, NodeUID: provider.NodeUID}
	identityRaw, _ := ce.Canonical(struct {
		Version  string
		Provider ma.Provider
	}{profile.Provider, sqlProvider})
	sqlProvider.IdentityHash = ma.Digest(hash(identityRaw))
	g := ma.SQLGrant{Version: ma.SQLGrantVersion, AuthorityID: in.AuthorityID, GrantID: in.GrantID, RecordRevision: 1, PermissionEpoch: 1, Target: target, Enrollment: enrollment, Actor: ma.Actor{LocalAdminUserID: f.grant.UserID, LocalAdminUsername: f.grant.Username, InstallerDatabaseAccount: "original_installer@localhost"}, ConfigSHA256: ma.Digest(f.config.SHA256()), BootstrapGrantSHA256: ma.Digest(f.input.GrantSHA256), Provider: sqlProvider, PermissionSource: permissionSource, Observation: ma.ObservationBinding{Profile: profile.Observation, DefinitionSHA256: ma.Digest(f.input.DefinitionSHA256), CapabilityIntentSHA256: ma.Digest(f.input.CapabilityIntentSHA256), MaximumAgeMicroseconds: ma.MaximumObservationAgeMicroseconds}, NotBefore: start, Until: end}
	byUse := map[string]minioPermissionUse{}
	for _, u := range p.uses {
		byUse[u.principal.Purpose] = u
	}
	for _, purpose := range []ma.Purpose{ma.ArtifactDelete, ma.ArtifactRead, ma.ArtifactWrite, ma.CatalogAppend, ma.CatalogRead} {
		u := byUse[string(purpose)]
		ref := ma.Reference{Purpose: purpose, IdentityHash: ma.Digest(u.principal.IdentityHash), IdentityVersion: u.principal.RefVersion, IdentityProfile: profile.Reference, ProviderIdentityHash: g.Provider.IdentityHash, ScopeProfile: profile.Scope, AccountSHA256: ma.Digest(u.principal.AccountSHA256), CredentialFileSHA256: ma.Digest(pins[string(purpose)]), CredentialLocatorSHA256: ma.Digest(hash([]byte(files[string(purpose)]))), PolicyName: u.principal.PolicyName, NormalizedPolicySHA256: ma.Digest(u.principal.PolicySHA256), Bucket: u.bucket, Root: u.root, StagingRoot: u.staging, CapabilityProfile: profile.Protocol, CapabilityIntentSHA256: g.Observation.CapabilityIntentSHA256, NotBefore: start, Until: now.Add(3 * time.Minute), ProtectedUntil: now.Add(4 * time.Minute)}
		switch purpose {
		case ma.ArtifactDelete:
			ref.Capability = "exact_delete"
		case ma.ArtifactRead:
			ref.Capability = "range_read"
		case ma.ArtifactWrite:
			ref.Capability = "conditional_create"
		case ma.CatalogAppend:
			ref.Capability = "append_record"
		case ma.CatalogRead:
			ref.Capability = "exact_read"
		}
		scopeRaw, _ := ce.Canonical(struct {
			Version                   string
			Purpose                   ma.Purpose
			Provider                  ma.Digest
			Bucket, Root, StagingRoot string
		}{profile.Scope, purpose, g.Provider.IdentityHash, ref.Bucket, ref.Root, ref.StagingRoot})
		ref.ScopeSHA256 = ma.Digest(hash(scopeRaw))
		descriptorFile, descriptorSHA := write(string(purpose)+".descriptor", MinIOBootstrapReferenceDescriptor{Version: profile.Reference, Reference: ref})
		ref.DescriptorSHA256 = ma.Digest(descriptorSHA)
		f.input.ReferenceFiles = append(f.input.ReferenceFiles, MinIOBootstrapReferenceFile{Purpose: purpose, File: descriptorFile})
		record := ma.SQLReferenceRecord{Version: ma.SQLReferenceVersion, AuthorityID: g.AuthorityID, GrantID: g.GrantID, RecordRevision: 1, PermissionEpoch: 1, Target: target, Enrollment: enrollment, ConfigSHA256: g.ConfigSHA256, Reference: ref}
		raw, err := ma.EncodeSQLReference(record)
		if err != nil {
			t.Fatal(err)
		}
		f.refs = append(f.refs, record)
		f.bundle.References = append(f.bundle.References, ma.SQLSignedReference{Purpose: purpose, Record: raw, Signature: ed25519.Sign(f.key, append([]byte(ma.SQLReferenceDomain), raw...))})
		g.References = append(g.References, ma.SQLReferenceHash{Purpose: purpose, SHA256: ma.Digest(hash(raw))})
	}
	refSet, _ := ce.Canonical(g.References)
	g.ReferenceSetSHA256 = ma.Digest(hash(refSet))
	f.declaration = g
	f.bundle.Grant, e = ma.EncodeSQLGrant(g)
	if e != nil {
		t.Fatal(e)
	}
	f.bundle.GrantSignature = ed25519.Sign(f.key, append([]byte(ma.SQLGrantDomain), f.bundle.Grant...))
	f.head = ma.SQLHead{Version: ma.SQLHeadVersion, AuthorityID: g.AuthorityID, Target: target, Enrollment: enrollment, HeadRevision: 1, PermissionEpoch: 1, CurrentGrantID: g.GrantID, CurrentGrantRevision: 1, GrantSHA256: ma.Digest(hash(f.bundle.Grant)), ReferenceSetSHA256: g.ReferenceSetSHA256, State: ma.StateActive, NotBefore: start, Until: end}
	f.bundle.Head, e = ma.EncodeSQLHead(f.head)
	if e != nil {
		t.Fatal(e)
	}
	f.bundle.HeadSignature = ed25519.Sign(f.key, append([]byte(ma.SQLHeadDomain), f.bundle.Head...))
	f.bundle.Version = ma.SQLBundleVersion
	f.bundle.Action = ma.SQLActionInstall
	f.bundle.PlanSHA256 = enrollment.PlanSHA256
	f.bundle.EnrollmentDocumentSHA256 = enrollment.DocumentSHA256
	f.input.Pin = ma.SQLTrustPin{Target: target, Enrollment: enrollment, AuthorityID: g.AuthorityID, GrantID: g.GrantID, GrantRevision: 1, MinimumHeadRevision: 1, MinimumPermissionEpoch: 1, GrantSHA256: f.head.GrantSHA256, ReferenceSetSHA256: g.ReferenceSetSHA256, IssuerPublic: f.public}
	bundleRaw, err := ma.EncodeSQLBundle(f.bundle)
	if err != nil {
		t.Fatal(err)
	}
	f.input.BundleFile, f.input.BundleSHA256 = writeRaw("sql-install.bundle", bundleRaw)
	plan := install.Plan{EnrollmentName: enrollment.ConfigMapName, OwnerUsername: enrollment.OwnerSubject, OwnerUID: enrollment.OwnerUID, Target: owner.Target{InstallationID: target.InstallationID, ClusterID: target.ClusterUID, Namespace: target.Namespace, NamespaceUID: target.NamespaceUID}}
	fixture := &minioProducerComponent{model: &producerComponentSQL{}, definition: definition}
	f.kube = minioProducerComponentKubernetes(t, fixture, plan, provider)
	for _, cm := range []*corev1.ConfigMap{{ObjectMeta: metav1.ObjectMeta{Name: permissionSource.Grant.Name, Namespace: target.Namespace, UID: types.UID(permissionSource.Grant.UID), ResourceVersion: "original-1"}, Data: map[string]string{"record.json": string(grantRaw)}, BinaryData: map[string][]byte{"signature": ed25519.Sign(f.key, append([]byte(minioPermissionOwnerDomain), grantRaw...))}}, {ObjectMeta: metav1.ObjectMeta{Name: permissionSource.Head.Name, Namespace: target.Namespace, UID: types.UID(permissionSource.Head.UID), ResourceVersion: "original-1"}, Data: map[string]string{"record.json": string(headRaw)}, BinaryData: map[string][]byte{"signature": ed25519.Sign(f.key, append([]byte(minioPermissionHeadDomain), headRaw...))}}} {
		if e = f.kube.Tracker().Create(corev1.SchemeGroupVersion.WithResource("configmaps"), cm, target.Namespace); e != nil {
			t.Fatal(e)
		}
	}
	f.kube.PrependReactor("*", "*", func(ktesting.Action) (bool, kruntime.Object, error) {
		if f.model.open.Load() != 0 {
			t.Error("concrete terminal performed Kubernetes I/O under SQL lock")
		}
		return false, nil, nil
	})
	f.resource, e = NewMinIOBootstrapTerminalResource(f.kube, f.input)
	if e != nil {
		t.Fatal("actual concrete terminal constructor", e)
	}
	return f
}
