const downloadAdmissionInstallationSQL = `SELECT origin_installation_id FROM system_backup_v2_evidence WHERE public_id=? FOR UPDATE`
const downloadAdmissionClaimCASSQL = `UPDATE system_backup_v2_evidence SET claim_owner=?,claim_expires_at=?,row_version=row_version+1,updated_at=UTC_TIMESTAMP(6)
WHERE public_id=? AND origin_installation_id=? AND row_version=? AND storage_state='ready' AND evidence_failure_code='none'
AND claim_owner <=> ? AND claim_expires_at <=> ?
AND ((claim_owner IS NULL AND claim_expires_at IS NULL) OR claim_expires_at<=UTC_TIMESTAMP(6))
AND UTC_TIMESTAMP(6)>=? AND UTC_TIMESTAMP(6)<? AND UTC_TIMESTAMP(6)<? AND UTC_TIMESTAMP(6)<?`

type DownloadAdmissionClaim struct {
	state        *downloadAdmissionClaimState
	registry     SQLRegistry
	tx           *sql.Tx
	key          *DownloadAdmissionKeyLock
	record       Record
	lastObserved time.Time
}
type downloadAdmissionClaimState struct {
	mu     sync.Mutex
	failed bool
}

func (*DownloadAdmissionClaim) MarshalJSON() ([]byte, error) { return nil, ErrInvalid }
func (*DownloadAdmissionClaim) String() string               { return "DownloadAdmissionClaim" }
func (*DownloadAdmissionClaim) GoString() string             { return "DownloadAdmissionClaim" }
func (c *DownloadAdmissionClaim) Record() Record {
	if c == nil {
		return Record{}
	}
	r := c.record
	r.Manifest.Chunks = append([]Chunk(nil), r.Manifest.Chunks...)
	return r
}

func (s SQLRegistry) loadDownloadAdmissionRecord(ctx context.Context, tx *sql.Tx, id string) (Record, error) {
	var installation sql.NullString
	if tx.QueryRowContext(ctx, downloadAdmissionInstallationSQL, id).Scan(&installation) != nil || !installation.Valid || installation.String != s.Installation {
		return Record{}, ErrDownloadAdmissionNotReady
	}
	r, err := s.load(ctx, tx, id)
	if err != nil {
		return Record{}, err
	}
	return r, nil
}
func sameDownloadAdmissionImmutable(a, b Record) bool {
	return hash(canonical(a.Manifest)) == hash(canonical(b.Manifest)) && a.Ref == b.Ref && a.CreatedAt.Equal(b.CreatedAt) &&
		a.ExpiresAt.Equal(b.ExpiresAt) && a.ProtectedUntil.Equal(b.ProtectedUntil) && a.OwnerDeadline.Equal(b.OwnerDeadline) && a.State == b.State && a.Failure == b.Failure
}

// StageDownloadAdmissionClaim performs only the original evidence claim CAS.
// D must already hold its full admission prefix and original intent audit. The
// claim string/absolute deadline are generated by D BEFORE the audit/evidence
// stage, not HTTP fields; waits never refresh the original thirty-second bound.
func (s SQLRegistry) StageDownloadAdmissionClaim(ctx context.Context, tx *sql.Tx, key *DownloadAdmissionKeyLock, expected Record, claim string, until time.Time) (*DownloadAdmissionClaim, error) {
	if key == nil || key.state == nil {
		return nil, ErrDownloadAdmissionNotReady
	}
	key.state.mu.Lock()
	defer key.state.mu.Unlock()
	if key.state.failed || key.state.staged || key.state.claimAttempted {
		return nil, ErrDownloadAdmissionNotReady
	}
	key.state.failed, key.state.claimAttempted = true, true
	if ctx == nil || ctx.Err() != nil || tx == nil || key.tx != tx || nilSystemAdapter(s.Policy) ||
		!downloadAdmissionClaimID.MatchString(claim) || !downloadAdmissionContentTime(until) || until.After(key.observedAt.Add(30*time.Second)) ||
		s.Installation != key.request.InstallationID() || expected.Manifest.Identity.Installation != s.Installation || !idPattern.MatchString(expected.Manifest.Identity.ID) ||
		expected.RowVersion < 1 || expected.RowVersion >= 9007199254740991 {
		return nil, ErrDownloadAdmissionNotReady
	}
	var server, database string
	if tx.QueryRowContext(ctx, "SELECT @@server_uuid,DATABASE()").Scan(&server, &database) != nil || server != s.ServerUUID || database != s.Database {
		return nil, ErrDownloadAdmissionNotReady
	}
	old, err := s.loadDownloadAdmissionRecord(ctx, tx, expected.Manifest.Identity.ID)
	if err != nil {
		return nil, err
	}
	if !sameDownloadAdmissionImmutable(old, expected) || old.RowVersion != expected.RowVersion || old.Claim != expected.Claim || !old.ClaimUntil.Equal(expected.ClaimUntil) ||
		hash(canonical(old.Manifest)) != key.request.ManifestSHA256() || !oneOf(old.Manifest.Identity.Classification, "confidential", "sensitive") || old.State != "ready" || old.Failure != "none" || !old.Ref.valid(true) {
		return nil, ErrState
	}
	now, err := downloadIntentNow(ctx, tx, key.observedAt)
	proofUntil, e := key.proof.AdmissionDeadlineAt()
	if err != nil || e != nil || !now.Before(until) || !downloadAdmissionActorAt(key.actor, now) || key.proof.RecheckProofAt(now) != nil {
		return nil, ErrDownloadAdmissionNotReady
	}
	if old.Claim != "" && (!downloadAdmissionClaimID.MatchString(old.Claim) || !downloadAdmissionContentTime(old.ClaimUntil) || now.Before(old.ClaimUntil)) || old.Claim == "" && !old.ClaimUntil.IsZero() || old.Manifest.Identity.Type == "job_log_chunk" && !now.Before(old.ExpiresAt) {
		return nil, ErrState
	}
	proofUntil = proofUntil.UTC().Truncate(time.Microsecond)
	result, err := tx.ExecContext(ctx, downloadAdmissionClaimCASSQL, claim, until, old.Manifest.Identity.ID, s.Installation, old.RowVersion, nullString(old.Claim), nullTime(old.ClaimUntil), now, until, proofUntil, key.actor.SessionExpiresAt)
	if !downloadAdmissionOne(result, err) {
		return nil, ErrConflict
	}
	admitted := old
	admitted.Claim, admitted.ClaimUntil, admitted.RowVersion = claim, until, old.RowVersion+1
	a := &DownloadAdmissionClaim{state: &downloadAdmissionClaimState{}, registry: s, tx: tx, key: key, record: admitted, lastObserved: now}
	if err = a.Recheck(ctx, tx); err != nil {
		return nil, err
	}
	key.state.failed = false
	return a, nil
}

func (c *DownloadAdmissionClaim) Recheck(ctx context.Context, tx *sql.Tx) error {
	if c == nil || c.state == nil {
		return ErrDownloadAdmissionNotReady
	}
	c.state.mu.Lock()
	defer c.state.mu.Unlock()
	if c.state.failed {
		return ErrDownloadAdmissionNotReady
	}
	c.state.failed = true
	if ctx == nil || ctx.Err() != nil || tx == nil || tx != c.tx || c.key == nil {
		return ErrDownloadAdmissionNotReady
	}
	r, err := c.registry.loadDownloadAdmissionRecord(ctx, tx, c.record.Manifest.Identity.ID)
	if err != nil || !sameDownloadAdmissionImmutable(r, c.record) || r.RowVersion != c.record.RowVersion || r.Claim != c.record.Claim || !r.ClaimUntil.Equal(c.record.ClaimUntil) {
		return ErrConflict
	}
	now, err := downloadIntentNow(ctx, tx, c.lastObserved)
	if err != nil || !now.Before(r.ClaimUntil) || !downloadAdmissionActorAt(c.key.actor, now) || c.key.proof.RecheckProofAt(now) != nil {
		return ErrDownloadAdmissionNotReady
	}
	c.lastObserved, c.state.failed = now, false
	return nil
}
