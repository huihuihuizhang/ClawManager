// Only the isolated legacy198 diagnostic uses this sorter. Ordinary import's
// existing budgets and digest are unchanged. Fixed-width hashes preserve row
// multiplicity; neither cells nor row payloads are written to scratch.
type legacy177HashSort struct {
	ctx               context.Context
	dir               string
	chunk             [][32]byte
	runs              []string
	levels            [][]string
	chunkLimit, fanIn int
	used, maxScratch  int64
}

var errLegacy177Scratch = errors.New("legacy177 row hash scratch budget exceeded")

func newLegacy177HashSort(ctx context.Context, chunkLimit, fanIn int, maxScratch int64) (*legacy177HashSort, error) {
	if ctx == nil || ctx.Err() != nil || chunkLimit < 1 || fanIn < 2 || fanIn > 32 || maxScratch < 32 {
		return nil, errLegacy177Scratch
	}
	dir, e := os.MkdirTemp("", "clawmanager-copy-row-hashes-")
	if e != nil {
		return nil, e
	}
	return &legacy177HashSort{ctx: ctx, dir: dir, chunkLimit: chunkLimit, fanIn: fanIn, maxScratch: maxScratch}, nil
}
func (s *legacy177HashSort) Close() error {
	if s == nil || !filepath.IsAbs(s.dir) || filepath.Clean(s.dir) != s.dir || !strings.HasPrefix(filepath.Base(s.dir), "clawmanager-copy-row-hashes-") {
		return errLegacy177Scratch
	}
	return os.RemoveAll(s.dir)
}
func (s *legacy177HashSort) add(hash [32]byte) error {
	if e := s.ctx.Err(); e != nil {
		return e
	}
	s.chunk = append(s.chunk, hash)
	if len(s.chunk) == s.chunkLimit {
		return s.flush()
	}
	return nil
}
func (s *legacy177HashSort) flush() error {
	if len(s.chunk) == 0 {
		return nil
	}
	if e := s.ctx.Err(); e != nil {
		return e
	}
	sort.Slice(s.chunk, func(a, b int) bool { return bytes.Compare(s.chunk[a][:], s.chunk[b][:]) < 0 })
	f, e := os.CreateTemp(s.dir, "run-")
	if e != nil {
		return e
	}
	writer := bufio.NewWriterSize(f, 64<<10)
	for _, hash := range s.chunk {
		if e = s.write(writer, hash[:]); e != nil {
			_ = f.Close()
			return e
		}
	}
	if e = writer.Flush(); e != nil {
		_ = f.Close()
		return e
	}
	if e = f.Close(); e != nil {
		return e
	}
	s.chunk = s.chunk[:0]
	return s.addRun(0, f.Name())
}
func (s *legacy177HashSort) addRun(level int, path string) error {
	for len(s.levels) <= level {
		s.levels = append(s.levels, nil)
	}
	s.levels[level] = append(s.levels[level], path)
	if len(s.levels[level]) < s.fanIn {
		return nil
	}
	next, e := s.merge(s.levels[level])
	if e != nil {
		return e
	}
	s.levels[level] = nil
	return s.addRun(level+1, next)
}
func (s *legacy177HashSort) write(w io.Writer, b []byte) error {
	if e := s.ctx.Err(); e != nil {
		return e
	}
	if int64(len(b)) > s.maxScratch-s.used {
		return errLegacy177Scratch
	}
	n, e := w.Write(b)
	s.used += int64(n)
	if e == nil && n != len(b) {
		e = io.ErrShortWrite
	}
	return e
}

type legacy177MergeItem struct {
	hash   [32]byte
	reader int
}
type legacy177MergeHeap []legacy177MergeItem

func (h legacy177MergeHeap) Len() int           { return len(h) }
func (h legacy177MergeHeap) Less(a, b int) bool { return bytes.Compare(h[a].hash[:], h[b].hash[:]) < 0 }
func (h legacy177MergeHeap) Swap(a, b int)      { h[a], h[b] = h[b], h[a] }
func (h *legacy177MergeHeap) Push(x any)        { *h = append(*h, x.(legacy177MergeItem)) }
func (h *legacy177MergeHeap) Pop() any {
	old := *h
	n := len(old)
	x := old[n-1]
	*h = old[:n-1]
	return x
}

func (s *legacy177HashSort) walk(paths []string, emit func([32]byte) error) (result error) {
	if len(paths) > s.fanIn {
		return errLegacy177Scratch
	}
	files := []*os.File{}
	defer func() {
		for _, f := range files {
			if e := f.Close(); e != nil && result == nil {
				result = e
			}
		}
	}()
	readers := []*bufio.Reader{}
	q := &legacy177MergeHeap{}
	for n, path := range paths {
		// Every pathname is generated by this object's private MkdirTemp.
		if filepath.Dir(path) != s.dir {
			return errLegacy177Scratch
		}
		f, e := os.Open(path)
		if e != nil {
			return e
		}
		files = append(files, f)
		r := bufio.NewReaderSize(f, 64<<10)
		readers = append(readers, r)
		var hash [32]byte
		_, e = io.ReadFull(r, hash[:])
		if e == io.EOF {
			continue
		}
		if e != nil {
			return e
		}
		heap.Push(q, legacy177MergeItem{hash, n})
	}
	for q.Len() > 0 {
		if e := s.ctx.Err(); e != nil {
			return e
		}
		item := heap.Pop(q).(legacy177MergeItem)
		if e := emit(item.hash); e != nil {
			return e
		}
		var next [32]byte
		_, e := io.ReadFull(readers[item.reader], next[:])
		if e == io.EOF {
			continue
		}
		if e != nil {
			return e
		}
		heap.Push(q, legacy177MergeItem{next, item.reader})
	}
	return nil
}
func (s *legacy177HashSort) merge(paths []string) (string, error) {
	f, e := os.CreateTemp(s.dir, "merge-")
	if e != nil {
		return "", e
	}
	w := bufio.NewWriterSize(f, 64<<10)
	e = s.walk(paths, func(h [32]byte) error { return s.write(w, h[:]) })
	if e == nil {
		e = w.Flush()
	}
	closeErr := f.Close()
	if e != nil {
		return "", e
	}
	if closeErr != nil {
		return "", closeErr
	}
	for _, path := range paths {
		st, e := os.Stat(path)
		if e != nil {
			return "", e
		}
		if e = os.Remove(path); e != nil {
			return "", e
		}
		s.used -= st.Size()
	}
	return f.Name(), nil
}
func (s *legacy177HashSort) digest(rows int64) (string, error) {
	if rows == 0 {
		if len(s.chunk) != 0 {
			return "", errors.New("legacy177 sorted row count differs")
		}
		for _, paths := range s.levels {
			if len(paths) != 0 {
				return "", errors.New("legacy177 sorted row count differs")
			}
		}
		return importDigest([]string(nil)), nil
	}
	if e := s.flush(); e != nil {
		return "", e
	}
	for _, paths := range s.levels {
		s.runs = append(s.runs, paths...)
	}
	for len(s.runs) > s.fanIn {
		next, e := s.merge(s.runs[:s.fanIn])
		if e != nil {
			return "", e
		}
		s.runs = append([]string{next}, s.runs[s.fanIn:]...)
	}
	h := sha256.New()
	_, _ = h.Write([]byte("["))
	var count int64
	e := s.walk(s.runs, func(row [32]byte) error {
		if count > 0 {
			_, _ = h.Write([]byte(","))
		}
		var encoded [66]byte
		encoded[0] = '"'
		hex.Encode(encoded[1:65], row[:])
		encoded[65] = '"'
		_, _ = h.Write(encoded[:])
		count++
		return nil
	})
	if e != nil {
		return "", e
	}
	if count != rows {
		return "", errors.New("legacy177 sorted row count differs")
	}
	_, _ = h.Write([]byte("]"))
	return hex.EncodeToString(h.Sum(nil)), nil
}
