func TestSecretBrokerPolicyClosesNamesAndLabels(t *testing.T) {
	cfg := SecretBrokerConfig{
		NamespacePrefix:   "clawmanager-zhanghui08",
		SystemNamespace:   "clawmanager-zhanghui08-system",
		AppNamespace:      "clawmanager-zhanghui08-system",
		AppServiceAccount: "clawmanager-app",
		ReadAllowlist:     []string{"external-secrets/model-key:token"},
	}
	policy, err := newSecretBrokerPolicy(cfg)
	if err != nil {
		t.Fatal(err)
	}
	tenant := (&Client{Namespace: cfg.NamespacePrefix}).GetNamespace(7)
	if tenant != "clawmanager-zhanghui08-user-7" {
		t.Fatalf("unexpected application tenant namespace %q", tenant)
	}
	team := &SecretRecord{
		Namespace: tenant,
		Name:      "clawreef-team-9-bus",
		Type:      corev1.SecretTypeOpaque,
		Data:      map[string][]byte{"CLAWMANAGER_TEAM_TOKEN": []byte("redacted")},
		Labels:    map[string]string{"managed-by": "clawreef", "team-id": "9"},
	}
	if err := policy.validateUpsert(team); err != nil {
		t.Fatalf("expected managed Team Secret to pass: %v", err)
	}
	team.Labels["team-id"] = "10"
	if err := policy.validateUpsert(team); err == nil {
		t.Fatal("mismatched Team id label must be denied")
	}
	if policy.allowValueRead("external-secrets", "model-key", "other") {
		t.Fatal("unregistered Secret key must be denied")
	}
	if !policy.allowValueRead("external-secrets", "model-key", "token") {
		t.Fatal("registered Secret key must be allowed")
	}
	if policy.allowDeleteByLabels(tenant, map[string]string{"managed-by": "clawreef"}) {
		t.Fatal("cleanup without an exact instance id must be denied")
	}
	if !policy.allowDeleteByLabels(tenant, map[string]string{"managed-by": "clawreef", "instance-id": "42"}) {
		t.Fatal("closed managed instance selector must be allowed")
	}
	team.Labels["team-id"] = "9"
	team.Namespace = "clawmanager-zhanghui08-system-user-7"
	if err := policy.validateUpsert(team); err == nil {
		t.Fatal("system-namespace-derived tenant is not generated by the application and must be denied")
	}
}

func TestSecretBrokerAuthenticatesProjectedAudienceAndReturnsOnlyRequestedValue(t *testing.T) {
	namespace := "clawmanager-zhanghui08-user-7"
	client := fake.NewSimpleClientset(&corev1.Secret{
		ObjectMeta: metav1.ObjectMeta{
			Namespace: namespace,
			Name:      "clawreef-team-9-bus",
			Labels:    map[string]string{"managed-by": "clawreef", "team-id": "9"},
		},
		Data: map[string][]byte{
			"CLAWMANAGER_TEAM_TOKEN":     []byte("requested"),
			"CLAWMANAGER_TEAM_REDIS_URL": []byte("must-not-be-returned"),
		},
	})
	client.PrependReactor("create", "tokenreviews", func(action k8stesting.Action) (bool, runtime.Object, error) {
		review := action.(k8stesting.CreateAction).GetObject().(*authenticationv1.TokenReview).DeepCopy()
		review.Status = authenticationv1.TokenReviewStatus{
			Authenticated: true,
			User:          authenticationv1.UserInfo{Username: "system:serviceaccount:clawmanager-zhanghui08-system:clawmanager-app"},
			Audiences:     []string{defaultSecretBrokerAudience},
		}
		return true, review, nil
	})
	handler, err := NewSecretBrokerHandler(client, SecretBrokerConfig{
		NamespacePrefix:   "clawmanager-zhanghui08",
		SystemNamespace:   "clawmanager-zhanghui08-system",
		AppNamespace:      "clawmanager-zhanghui08-system",
		AppServiceAccount: "clawmanager-app",
	})
	if err != nil {
		t.Fatal(err)
	}
	body, _ := json.Marshal(map[string]string{
		"namespace": namespace,
		"name":      "clawreef-team-9-bus",
		"key":       "CLAWMANAGER_TEAM_TOKEN",
	})
	request := httptest.NewRequest(http.MethodPost, "/v1/secrets/get-value", bytes.NewReader(body))
	request.Header.Set("Authorization", "Bearer projected-token")
	response := httptest.NewRecorder()
	handler.ServeHTTP(response, request)
	if response.Code != http.StatusOK {
		t.Fatalf("unexpected status %d: %s", response.Code, response.Body.String())
	}
	var result struct {
		Value []byte `json:"value"`
	}
	if err := json.Unmarshal(response.Body.Bytes(), &result); err != nil {
		t.Fatal(err)
	}
	if string(result.Value) != "requested" || bytes.Contains(response.Body.Bytes(), []byte("must-not-be-returned")) {
		t.Fatalf("broker returned an unexpected Secret projection: %q", response.Body.String())
	}

	unauthenticated := httptest.NewRecorder()
	handler.ServeHTTP(unauthenticated, httptest.NewRequest(http.MethodPost, "/v1/secrets/get-value", bytes.NewReader(body)))
	if unauthenticated.Code != http.StatusUnauthorized {
		t.Fatalf("missing token must be rejected, got %d", unauthenticated.Code)
	}
}

func TestSecretBrokerRejectsManagedPointOperationsWhenStoredOwnershipLabelsAreInvalid(t *testing.T) {
	namespace := "clawmanager-zhanghui08-user-7"
	tests := []struct {
		name   string
		labels map[string]string
	}{
		{name: "missing labels", labels: nil},
		{name: "mismatched team id", labels: map[string]string{"managed-by": "clawreef", "team-id": "10"}},
		{name: "wrong manager", labels: map[string]string{"managed-by": "someone-else", "team-id": "9"}},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			client := fake.NewSimpleClientset(&corev1.Secret{
				ObjectMeta: metav1.ObjectMeta{
					Namespace: namespace,
					Name:      "clawreef-team-9-bus",
					Labels:    test.labels,
				},
				Data: map[string][]byte{"CLAWMANAGER_TEAM_TOKEN": []byte("redacted")},
			})
			allowBrokerAppIdentity(client)
			handler, err := NewSecretBrokerHandler(client, SecretBrokerConfig{
				NamespacePrefix:   "clawmanager-zhanghui08",
				SystemNamespace:   "clawmanager-zhanghui08-system",
				AppNamespace:      "clawmanager-zhanghui08-system",
				AppServiceAccount: "clawmanager-app",
			})
			if err != nil {
				t.Fatal(err)
			}

			requests := []struct {
				path string
				body map[string]string
			}{
				{path: "/v1/secrets/get", body: map[string]string{"namespace": namespace, "name": "clawreef-team-9-bus"}},
				{path: "/v1/secrets/get-value", body: map[string]string{"namespace": namespace, "name": "clawreef-team-9-bus", "key": "CLAWMANAGER_TEAM_TOKEN"}},
				{path: "/v1/secrets/delete", body: map[string]string{"namespace": namespace, "name": "clawreef-team-9-bus"}},
			}
			for _, requestCase := range requests {
				body, err := json.Marshal(requestCase.body)
				if err != nil {
					t.Fatal(err)
				}
				request := httptest.NewRequest(http.MethodPost, requestCase.path, bytes.NewReader(body))
				request.Header.Set("Authorization", "Bearer projected-token")
				response := httptest.NewRecorder()
				handler.ServeHTTP(response, request)
				if response.Code != http.StatusForbidden {
					t.Fatalf("%s must reject invalid stored ownership labels, got %d: %s", requestCase.path, response.Code, response.Body.String())
				}
			}
			if _, err := client.CoreV1().Secrets(namespace).Get(context.Background(), "clawreef-team-9-bus", metav1.GetOptions{}); err != nil {
				t.Fatalf("rejected point delete must leave the Secret intact: %v", err)
			}
		})
	}
}

func allowBrokerAppIdentity(client *fake.Clientset) {
	client.PrependReactor("create", "tokenreviews", func(action k8stesting.Action) (bool, runtime.Object, error) {
		review := action.(k8stesting.CreateAction).GetObject().(*authenticationv1.TokenReview).DeepCopy()
		review.Status = authenticationv1.TokenReviewStatus{
			Authenticated: true,
			User:          authenticationv1.UserInfo{Username: "system:serviceaccount:clawmanager-zhanghui08-system:clawmanager-app"},
			Audiences:     []string{defaultSecretBrokerAudience},
		}
		return true, review, nil
	})
}

func TestDirectSecretStoreDeleteByLabelsDoesNotDeleteUnmatchedSecrets(t *testing.T) {
	client := fake.NewSimpleClientset(
		&corev1.Secret{ObjectMeta: metav1.ObjectMeta{Namespace: "tenant", Name: "matched", Labels: map[string]string{"managed-by": "clawreef", "instance-id": "7"}}},
		&corev1.Secret{ObjectMeta: metav1.ObjectMeta{Namespace: "tenant", Name: "other", Labels: map[string]string{"managed-by": "clawreef", "instance-id": "8"}}},
	)
	store := &directSecretStore{client: &Client{Clientset: client}}
	if err := store.DeleteByLabels(context.Background(), "tenant", map[string]string{"managed-by": "clawreef", "instance-id": "7"}); err != nil {
		t.Fatal(err)
	}
	if _, err := client.CoreV1().Secrets("tenant").Get(context.Background(), "other", metav1.GetOptions{}); err != nil {
		t.Fatalf("unmatched Secret must remain: %v", err)
	}
}

func TestBrokerClientRequiresPinnedCAForHTTPS(t *testing.T) {
	t.Setenv(secretBrokerCAFileEnv, "")
	t.Setenv(secretBrokerAllowInsecureHTTPForTestsEnv, "")
	if _, err := newBrokerSecretStore("https://clawmanager-secret-broker.example:9444", "token"); err == nil {
		t.Fatal("HTTPS broker client must require an explicit CA file")
	}
	if _, err := newBrokerSecretStore("http://clawmanager-secret-broker:9444", "token"); err == nil {
		t.Fatal("HTTP must be rejected unless the explicit test-only switch is enabled")
	}
	t.Setenv(secretBrokerAllowInsecureHTTPForTestsEnv, "true")
	if _, err := newBrokerSecretStore("http://clawmanager-secret-broker:9444", "token"); err != nil {
		t.Fatalf("HTTP must be available only with the explicit test switch: %v", err)
	}
}
